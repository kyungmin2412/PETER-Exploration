const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const m = require('./ipo-model.js');
const html = fs.readFileSync(__dirname + '/index.html', 'utf8');
for (const match of html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
new vm.Script(fs.readFileSync(__dirname + '/ipo.js', 'utf8'));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(x => x[1]);
assert.equal(new Set(ids).size, ids.length, 'DOM IDs must be unique');
const r = {id:'sample',company:'테스트기업',broker:'테스트증권',subscriptionStart:'2026-10-30',subscriptionEnd:'2026-11-02',refundDate:'2026-11-04',listingDate:'2026-11-10'};
assert.equal(m.validate(r), '');
assert.equal(m.occurrences(r, '2026-10-29').length, 0);
for (const d of ['2026-10-30','2026-10-31','2026-11-01','2026-11-02']) assert.equal(m.occurrences(r,d)[0].key, 'subscription');
assert.equal(m.occurrences(r,'2026-11-03').length,0);
assert.equal(m.occurrences(r,'2026-11-04')[0].key,'refund');
assert.equal(m.occurrences(r,'2026-11-10','subscription').length,0);
assert.equal(m.occurrences({...r,deleted:true},'2026-10-30').length,0);
assert.ok(m.matches(r,'테스트증권'));
assert.ok(m.validDate('2028-02-29'));
assert.ok(!m.validDate('2026-02-29'));
assert.ok(m.validate({...r,subscriptionEnd:'2026-10-29'}));
assert.ok(m.validate({...r,subscriptionEnd:''}));
assert.ok(m.validate({company:'기업'}));
assert.ok(m.validate({...r,sourceUrl:'javascript:alert(1)'}));
assert.equal(m.validate({...r,sourceUrl:'https://example.com/ipo'}), '');
assert.throws(()=>m.parseFile({truncated:true,content:'{}'}));
assert.throws(()=>m.parseFile({content:'{"version":9,"items":{}}'}));
assert.throws(()=>m.parseFile({content:'{"version":1,"items":[]}'}));
const base={sample:r,other:{id:'other',company:'별도기업'}};
const changed={sample:{...r,price:'10,000원'}};
const merged=m.merge(base,changed);
assert.equal(merged.other,base.other);
assert.equal(base.sample.price,undefined);
assert.equal(merged.sample.price,'10,000원');
assert.deepEqual(m.parseFile({content:JSON.stringify({version:1,items:merged})}),merged);
console.log('PASS: script syntax, unique IDs, date boundaries, filters, validation, schema and independent-record merges');
